# DSH browser-session cookie minting (Windows PowerShell 5.1+).
#
# Reverse-engineered from the DSH desktop bundle: the browser credential is
#   name  = "dsh-auth-" + base64url(sha256(authority))
#   value = "v1." + base64url(json(payload)) + "." + base64url(hmac_sha256(secret, body))
# with payload {version:1, authority, issuedAt, expiresAt}, authority = the Host
# header value (no scheme), and secret = the 32-byte key stored in
# %USERPROFILE%\.dsh\.credentials.yaml under client-connection/browser-session.
#
# SECURITY: the output is a live bearer credential (max 30 days). Keep it in
# dsh-cookie.inc (mode 600 / owner-only ACL) and never commit it.
#
# Examples:
#   .\mint-cookie.ps1 -Authority dsh.example.com -PrintCookie
#   .\mint-cookie.ps1 -Authority dsh.example.com -WriteInc .\dsh-cookie.inc
#   .\mint-cookie.ps1 -Authority dsh.example.com -VerifyUrl http://127.0.0.1:<port>

[CmdletBinding()]
param(
  [Parameter(Mandatory = $true)][string]$Authority,
  [string]$Credentials = (Join-Path $HOME '.dsh\.credentials.yaml'),
  [ValidateRange(1, 30)][int]$Days = 30,
  [switch]$PrintCookie,
  [string]$WriteInc,
  [switch]$NoSecure,
  [string]$VerifyUrl
)

$ErrorActionPreference = 'Stop'
$record = 'client-connection/browser-session'

function ConvertTo-Base64Url {
  param([byte[]]$Bytes)
  return [Convert]::ToBase64String($Bytes).TrimEnd('=').Replace('+', '-').Replace('/', '_')
}

function ConvertFrom-Base64Url {
  param([string]$Text)
  $value = $Text.Replace('-', '+').Replace('_', '/')
  switch ($value.Length % 4) {
    2 { $value += '==' }
    3 { $value += '=' }
    1 { throw 'invalid base64url value' }
  }
  return [Convert]::FromBase64String($value)
}

function Get-BrowserSessionSecret {
  param([string]$Path)
  if (-not (Test-Path -LiteralPath $Path)) {
    throw "DSH credentials not found at $Path. Start the DSH desktop app once so it creates the file, or pass -Credentials."
  }
  $text = [System.IO.File]::ReadAllText($Path)
  $match = [regex]::Match($text, '(?m)^(?<indent>[ \t]*)"?' + [regex]::Escape($record) + '"?\s*:\s*$')
  if (-not $match.Success) {
    throw "credential record '$record' not found in $Path; start the DSH desktop app once."
  }
  $baseIndent = $match.Groups['indent'].Value.Length
  $blockLines = New-Object System.Collections.Generic.List[string]
  foreach ($line in $text.Substring($match.Index + $match.Length).Split("`n")) {
    $trimmed = $line.TrimEnd("`r")
    if ($trimmed.Trim() -eq '') { continue }
    $indent = [regex]::Match($trimmed, '^\s*').Length
    if ($indent -le $baseIndent) { break }
    $blockLines.Add($trimmed)
  }
  $block = $blockLines -join "`n"
  if ($block -notmatch '(?m)^\s+kind:\s*"?grant"?\s*$') {
    throw "credential record '$record' is not a grant record"
  }
  $secretMatch = [regex]::Match($block, '(?m)^\s+secret:\s*"?([A-Za-z0-9_-]+)"?\s*$')
  if (-not $secretMatch.Success) { throw "credential record '$record' has no payload.secret" }
  $secret = ConvertFrom-Base64Url $secretMatch.Groups[1].Value
  if ($secret.Length -ne 32) { throw "browser-session secret is not 32 bytes" }
  return $secret
}

if ($Authority -notmatch '^[A-Za-z0-9.-]+(?::[0-9]{1,5})?$') {
  throw '-Authority must be a bare Host value such as dsh.example.com (no scheme, no path)'
}

$secretBytes = Get-BrowserSessionSecret -Path $Credentials
$issuedAt = [DateTimeOffset]::UtcNow.ToUnixTimeMilliseconds()
$expiresAt = $issuedAt + ([int64]$Days * 86400000)
$payload = [ordered]@{
  version   = 1
  authority = $Authority
  issuedAt  = $issuedAt
  expiresAt = $expiresAt
}
$json = $payload | ConvertTo-Json -Compress
$body = ConvertTo-Base64Url ([System.Text.Encoding]::UTF8.GetBytes($json))
# NOTE: [HMACSHA256]::Create() on Windows PowerShell 5.1 returns HMACSHA1
# (HashSize 160) - use the explicit constructor so the signature is SHA-256.
$hmac = [System.Security.Cryptography.HMACSHA256]::new($secretBytes)
$signature = ConvertTo-Base64Url ($hmac.ComputeHash([System.Text.Encoding]::ASCII.GetBytes($body)))
$hmac.Dispose()
$sha = [System.Security.Cryptography.SHA256]::Create()
$name = 'dsh-auth-' + (ConvertTo-Base64Url ($sha.ComputeHash([System.Text.Encoding]::UTF8.GetBytes($Authority))))
$sha.Dispose()
$cookie = "$name=v1.$body.$signature"

$attributes = "$cookie; Max-Age=$($Days * 86400); Path=/; HttpOnly; SameSite=Strict"
if (-not $NoSecure) { $attributes += '; Secure' }

if ($PrintCookie) {
  Write-Output $cookie
  return
}

if ($WriteInc) {
  $header = @(
    "# DSH browser-session cookie, minted $(Get-Date -Format 'yyyy-MM-dd HH:mm:ss') for $Authority (valid until $([DateTimeOffset]::FromUnixTimeMilliseconds($expiresAt).LocalDateTime.ToString('yyyy-MM-dd HH:mm'))).",
    '# Generated by dsh-remote; contains a live credential, keep it owner-only and never commit it.'
  )
  $content = ($header -join "`r`n") + "`r`n" + 'set $dsh_cookie "' + $attributes + '";' + "`r`n"
  $directory = Split-Path -Parent $WriteInc
  if ($directory -and -not (Test-Path -LiteralPath $directory)) {
    New-Item -ItemType Directory -Force -Path $directory | Out-Null
  }
  [System.IO.File]::WriteAllText($WriteInc, $content, (New-Object System.Text.UTF8Encoding($false)))
  Write-Verbose "wrote $WriteInc (valid until $([DateTimeOffset]::FromUnixTimeMilliseconds($expiresAt).LocalDateTime))"
}

if ($VerifyUrl) {
  $curl = Get-Command curl.exe -ErrorAction SilentlyContinue
  if ($null -eq $curl) {
    Write-Warning 'curl.exe not found; skipping -VerifyUrl check'
  } else {
    $status = & $curl.Source -s -o NUL -w '%{http_code}' --max-time 10 `
      -H "Host: $Authority" -H "Cookie: $cookie" $VerifyUrl
    if ($status -ne '200') {
      throw "cookie was rejected by $VerifyUrl (HTTP $status); confirm -Authority matches the Host header the listener receives and that this profile uses $Credentials"
    }
    Write-Verbose "verify $VerifyUrl -> HTTP 200"
  }
}

if (-not $PrintCookie -and -not $WriteInc -and -not $VerifyUrl) {
  Write-Output $cookie
}
